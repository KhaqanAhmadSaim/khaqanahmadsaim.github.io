<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Not fixing a person. Walking alongside them.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The name holds the heart of our work. <strong>Own</strong> is about owning your story, with honesty and self-compassion. <strong>Become</strong> is about growing into who you’re choosing to be. Together, they stand for resilience: not fixing a person, but walking alongside them as they grow through difficulty.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Our logo shows two figures leaning toward each other to form a single leaf, with a small new leaf growing between them. That’s how we see therapy: a relationship built on trust and shared effort, where something new can grow.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>I started Own &amp; Become out of a desire to create a space where people feel heard, supported, and comfortable showing up as they are. I hope to support individuals and couples as they navigate life’s challenges, relationships, transitions, and the many experiences that shape who we are. My vision is to offer a compassionate, collaborative space where clients can better understand themselves, work towards their personal goals, and feel empowered to grow and become more connected with themselves and others.</p>
