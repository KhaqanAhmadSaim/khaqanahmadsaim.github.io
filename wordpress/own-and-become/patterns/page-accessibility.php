<p>Own &amp; Become is committed to making this website welcoming and usable for everyone, including people with disabilities. We aim to meet the Web Content Accessibility Guidelines (WCAG) 2.2 at Level AA, consistent with the Accessibility for Ontarians with Disabilities Act (AODA).</p>
<!-- /wp:paragraph -->

